"""The Clash listener tool must never be able to leave a configuration that
does not start, and must put the previous files back when it cannot."""

from __future__ import annotations

import contextlib
import io
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import yaml

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "tools"))

import setup_clash_listeners as tool  # noqa: E402

VERGE_DIRECTORY_NAME = "io.github.clash-verge-rev.clash-verge-rev"
MERGE_FILENAME = "merge.yaml"
NODE_A = "香港 01 HKIX"
NODE_B = "日本 01 NTTドコモ"
RUNTIME_CONFIGURATION = "# Generated by Clash Verge\n\nmixed-port: 7897\nsecret: test-secret\nrules:\n- MATCH,DIRECT\n"
MERGE_CONFIGURATION = "# Profile Enhancement Merge Template for Clash Verge\n"
PROFILES_INDEX = """
current: SUB1
items:
- uid: SUB1
  type: remote
  name: subscription.yaml
  file: subscription.yaml
  option:
    merge: MERGE1
- uid: MERGE1
  type: merge
  file: merge.yaml
"""


class SetupClashListenersTests(unittest.TestCase):
    def setUp(self) -> None:
        self._temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self._temporary.cleanup)
        appdata = Path(self._temporary.name) / "AppData"
        self.verge = appdata / VERGE_DIRECTORY_NAME
        (self.verge / "profiles").mkdir(parents=True)
        self.runtime = self.verge / "clash-verge.yaml"
        self.merge = self.verge / "profiles" / MERGE_FILENAME
        self._write(self.runtime, RUNTIME_CONFIGURATION)
        self._write(self.merge, MERGE_CONFIGURATION)
        self._write(self.verge / "profiles.yaml", PROFILES_INDEX)

        self._patch_dictionary(os.environ, {"APPDATA": str(appdata)})
        self._patch(tool.mihomo_controller, "list_proxy_names",
                    mock.Mock(return_value=[NODE_A, NODE_B]))
        self._patch(tool.mihomo_controller, "reload_runtime_config",
                    mock.Mock(return_value=(204, b"")))

    def _patch(self, target, attribute: str, new) -> None:
        patcher = mock.patch.object(target, attribute, new)
        patcher.start()
        self.addCleanup(patcher.stop)

    def _patch_dictionary(self, target, values: dict) -> None:
        patcher = mock.patch.dict(target, values)
        patcher.start()
        self.addCleanup(patcher.stop)

    def _write(self, path: Path, content: str) -> None:
        path.write_text(content, encoding="utf-8", newline="\n")

    def run_tool(self, *arguments: str) -> int:
        argv = ["setup_clash_listeners.py", "--no-verify", *arguments]
        out, err = io.StringIO(), io.StringIO()
        with mock.patch.object(sys, "argv", argv), contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            status = tool.main()
        self.stdout, self.stderr = out.getvalue(), err.getvalue()
        return status

    def standard_arguments(self, node_a: str = NODE_A, node_b: str = NODE_B) -> tuple[str, ...]:
        return ("--listener", "keymux-route-a", "7893", node_a,
                "--listener", "keymux-route-b", "7894", node_b)

    def test_writes_one_listeners_block_and_is_idempotent(self) -> None:
        self.assertEqual(self.run_tool(*self.standard_arguments()), 0)
        first = self.merge.read_text(encoding="utf-8")
        self.assertEqual(self.run_tool(*self.standard_arguments()), 0)

        content = self.merge.read_text(encoding="utf-8")
        self.assertEqual(content.count("listeners:"), 1)
        self.assertEqual(content, first)
        document = yaml.safe_load(content)
        self.assertEqual([item["proxy"] for item in document["listeners"]], [NODE_A, NODE_B])
        self.assertEqual(yaml.safe_load(self.runtime.read_text(encoding="utf-8"))["listeners"][0]["port"], 7893)

    def test_a_node_name_with_quotes_round_trips(self) -> None:
        quoted = 'odd "quoted" node #1'
        self._patch(tool.mihomo_controller, "list_proxy_names",
                    mock.Mock(return_value=[quoted, NODE_B]))

        self.assertEqual(self.run_tool(*self.standard_arguments(node_a=quoted)), 0)

        document = yaml.safe_load(self.merge.read_text(encoding="utf-8"))
        self.assertEqual(document["listeners"][0]["proxy"], quoted)

    def test_an_unknown_node_is_refused_before_anything_is_written(self) -> None:
        with self.assertRaises(SystemExit):
            self.run_tool(*self.standard_arguments(node_a="does not exist"))

        self.assertEqual(self.merge.read_text(encoding="utf-8"), MERGE_CONFIGURATION)
        self.assertEqual(self.runtime.read_text(encoding="utf-8"), RUNTIME_CONFIGURATION)

    def test_a_foreign_listeners_section_is_refused(self) -> None:
        for foreign in ("listeners: []\n", "listeners: {}\n", "listeners: # mine\n  - name: mine\n"):
            with self.subTest(foreign=foreign):
                self._write(self.merge, MERGE_CONFIGURATION + foreign)
                with self.assertRaises(SystemExit):
                    self.run_tool(*self.standard_arguments())
                self.assertEqual(self.runtime.read_text(encoding="utf-8"), RUNTIME_CONFIGURATION)

    def test_an_out_of_range_port_is_refused(self) -> None:
        for port in ("0", "65536", "not-a-port", "-1"):
            with self.subTest(port=port):
                with self.assertRaises(SystemExit):
                    self.run_tool(
                        "--listener", "keymux-route-a", port, NODE_A,
                        "--listener", "keymux-route-b", "7894", NODE_B,
                    )

    def test_duplicate_ports_are_refused(self) -> None:
        with self.assertRaises(SystemExit):
            self.run_tool("--listener", "route-a", "7893", NODE_A,
                          "--listener", "route-b", "7893", NODE_B)

        self.assertEqual(self.merge.read_text(encoding="utf-8"), MERGE_CONFIGURATION)

    def test_duplicate_names_are_refused(self) -> None:
        with self.assertRaises(SystemExit):
            self.run_tool("--listener", "same", "7893", NODE_A,
                          "--listener", "same", "7894", NODE_B)

    def test_a_rejected_reload_restores_both_files(self) -> None:
        self._patch(tool.mihomo_controller, "reload_runtime_config", mock.Mock(return_value=(500, b"bad config")))

        self.assertEqual(self.run_tool(*self.standard_arguments()), 1)

        self.assertIn("rejected", self.stderr)
        self.assertIn("restored", self.stderr)
        self.assertEqual(self.merge.read_text(encoding="utf-8"), MERGE_CONFIGURATION)
        self.assertEqual(self.runtime.read_text(encoding="utf-8"), RUNTIME_CONFIGURATION)

    def test_a_missing_merge_file_is_removed_again_when_the_reload_is_rejected(self) -> None:
        self.merge.unlink()
        self._patch(tool.mihomo_controller, "reload_runtime_config", mock.Mock(return_value=(500, b"bad config")))

        self.assertEqual(self.run_tool(*self.standard_arguments()), 1)

        self.assertFalse(self.merge.exists())
        self.assertEqual(self.runtime.read_text(encoding="utf-8"), RUNTIME_CONFIGURATION)


if __name__ == "__main__":
    unittest.main()
